import Foundation

/// Risk level for legacy SDKs
public enum LegacySDKRisk: String, Sendable {
    case low
    case medium
    case high
    case critical
    
    public var priority: Int {
        switch self {
        case .low: return 1
        case .medium: return 2
        case .high: return 3
        case .critical: return 4
        }
    }
    
    public var emoji: String {
        switch self {
        case .low: return "🟢"
        case .medium: return "🟡"
        case .high: return "🟠"
        case .critical: return "🔴"
        }
    }
    
    public var description: String {
        switch self {
        case .low: return "Low Risk"
        case .medium: return "Medium Risk"
        case .high: return "High Risk"
        case .critical: return "Critical Risk"
        }
    }
}

/// Legacy SDK detected during migration
public struct LegacySDK: Sendable {
    public let name: String
    public let detectionMethod: String
    public let riskLevel: LegacySDKRisk
    public let suggestedCategory: String
    public let typicalInitCall: String?
    public let version: String?
    public let alternativeAdapters: [String]?
    
    public init(
        name: String,
        detectionMethod: String,
        riskLevel: LegacySDKRisk,
        suggestedCategory: String,
        typicalInitCall: String? = nil,
        version: String? = nil,
        alternativeAdapters: [String]? = nil
    ) {
        self.name = name
        self.detectionMethod = detectionMethod
        self.riskLevel = riskLevel
        self.suggestedCategory = suggestedCategory
        self.typicalInitCall = typicalInitCall
        self.version = version
        self.alternativeAdapters = alternativeAdapters
    }
}

/// Report generated by migration assistant
public struct MigrationReport: Sendable {
    public let detectedSDKs: [LegacySDK]
    public let isMigrationReady: Bool
    public let recommendations: [String]
    public let generatedCode: String?
    public let warnings: [String]
    public let errors: [String]
    public let timestamp: Date
    
    public init(
        detectedSDKs: [LegacySDK],
        isMigrationReady: Bool,
        recommendations: [String],
        generatedCode: String? = nil,
        warnings: [String] = [],
        errors: [String] = [],
        timestamp: Date = Date()
    ) {
        self.detectedSDKs = detectedSDKs
        self.isMigrationReady = isMigrationReady
        self.recommendations = recommendations
        self.generatedCode = generatedCode
        self.warnings = warnings
        self.errors = errors
        self.timestamp = timestamp
    }
    
    /// Get a formatted report string
    public func formatted() -> String {
        var output = ""
        
        // Header
        output += "========================================\n"
        output += "🍪 CookiePrime Migration Report\n"
        output += "========================================\n"
        output += "Generated: \(DateFormatter.localizedString(from: timestamp, dateStyle: .medium, timeStyle: .medium))\n"
        output += "========================================\n\n"
        
        // Errors
        if !errors.isEmpty {
            output += "❌ ERRORS:\n"
            for error in errors {
                output += "  • \(error)\n"
            }
            output += "\n"
        }
        
        // Warnings
        if !warnings.isEmpty {
            output += "⚠️ WARNINGS:\n"
            for warning in warnings {
                output += "  • \(warning)\n"
            }
            output += "\n"
        }
        
        // Detected SDKs
        if detectedSDKs.isEmpty {
            output += "✅ No legacy SDKs detected.\n"
            output += "   Your app is ready for deferred initialization mode!\n\n"
        } else {
            output += "📦 LEGACY SDKs DETECTED (\(detectedSDKs.count)):\n"
            output += "----------------------------------------\n"
            
            for sdk in detectedSDKs {
                output += "  \(sdk.riskLevel.emoji) \(sdk.name)\n"
                output += "    Risk Level: \(sdk.riskLevel.description)\n"
                output += "    Detection: \(sdk.detectionMethod)\n"
                output += "    Category: \(sdk.suggestedCategory)\n"
                
                if let initCall = sdk.typicalInitCall {
                    output += "    Typical Init: \(initCall)\n"
                }
                
                if let adapters = sdk.alternativeAdapters, !adapters.isEmpty {
                    output += "    Suggested Adapters: \(adapters.joined(separator: ", "))\n"
                }
                
                if let version = sdk.version {
                    output += "    Version: \(version)\n"
                }
                
                output += "\n"
            }
        }
        
        // Recommendations
        if !recommendations.isEmpty {
            output += "📋 RECOMMENDATIONS:\n"
            output += "----------------------------------------\n"
            for recommendation in recommendations {
                output += "  • \(recommendation)\n"
            }
            output += "\n"
        }
        
        // Generated Code
        if let code = generatedCode {
            output += "💻 GENERATED MIGRATION CODE:\n"
            output += "----------------------------------------\n"
            output += code
            output += "\n"
        }
        
        // Status
        output += "----------------------------------------\n"
        output += "Migration Ready: \(isMigrationReady ? "✅ YES" : "⚠️ NO")\n"
        output += "========================================\n"
        
        return output
    }
    
    /// Get a JSON representation of the report
    public func toJSON() -> String? {
        let encoder = JSONEncoder()
        encoder.outputFormatting = .prettyPrinted
        encoder.dateEncodingStrategy = .iso8601
        
        let data: [String: Any] = [
            "detectedSDKs": detectedSDKs.map { sdk in
                [
                    "name": sdk.name,
                    "detectionMethod": sdk.detectionMethod,
                    "riskLevel": sdk.riskLevel.rawValue,
                    "suggestedCategory": sdk.suggestedCategory,
                    "typicalInitCall": sdk.typicalInitCall ?? "",
                    "version": sdk.version ?? "",
                    "alternativeAdapters": sdk.alternativeAdapters ?? []
                ]
            },
            "isMigrationReady": isMigrationReady,
            "recommendations": recommendations,
            "warnings": warnings,
            "errors": errors,
            "timestamp": ISO8601DateFormatter().string(from: timestamp)
        ]
        
        guard let jsonData = try? JSONSerialization.data(withJSONObject: data, options: .prettyPrinted) else {
            return nil
        }
        
        return String(data: jsonData, encoding: .utf8)
    }
}

// MARK: - DateFormatter Extension

private extension DateFormatter {
    static let iso8601: DateFormatter = {
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd HH:mm:ss"
        formatter.timeZone = TimeZone.current
        return formatter
    }()
}